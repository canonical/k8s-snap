"""Generate Markdown references from charmcraft.yaml files."""

import argparse
import json
import sys
import textwrap
from pathlib import Path

import yaml


def other_settings_lines(schema, exclude=()):
    extra = {
        key: value
        for key, value in schema.items()
        if key not in {"type", "default", "description", *exclude}
    }
    if not extra:
        return []
    return [
        "**Other settings:**",
        "",
        "````yaml",
        yaml.safe_dump(extra).rstrip(),
        "````",
        "",
    ]


def default_text(schema):
    return f"default ``{json.dumps(schema['default'])}``" if "default" in schema else ""


def field_lines(schema, exclude=()):
    lines = []
    meta = [f"`{schema['type']}`"] if "type" in schema else []
    meta.append(default_text(schema))
    meta = [part for part in meta if part]
    if meta:
        lines.extend([" · ".join(meta), ""])
    if schema.get("description"):
        lines.extend([schema["description"].strip(), ""])
    lines.extend(other_settings_lines(schema, exclude))
    return lines


def parameter_lines(param, schema, required):
    meta = [f"`{schema['type']}`"] if "type" in schema else []
    meta += ["required" if required else "optional", default_text(schema)]
    text = f"`{param}` ({', '.join(part for part in meta if part)})"
    if schema.get("description"):
        text += f": {schema['description'].strip()}"
    extra = "\n".join(other_settings_lines(schema)[:-1])
    if extra:
        text += "\n\n" + extra
    # Indent every line, then swap the first line's indent for the bullet marker.
    return ("- " + textwrap.indent(text, "  ")[2:]).split("\n")


HEADER = ["<!-- Generated by generate_charms_reference.py; do not edit. -->", ""]


def render_config(name, options):
    lines = list(HEADER)
    for option, schema in sorted(options.items()):
        lines.extend([f"({name}-config-{option})=", f"### `{option}`", ""])
        lines.extend(field_lines(schema))
    if not options:
        lines.extend(["This charm declares no configuration options.", ""])
    return "\n".join(lines)


def render_actions(name, actions):
    lines = list(HEADER)
    for action, schema in sorted(actions.items()):
        lines.extend([f"({name}-action-{action})=", f"### `{action}`", ""])
        lines.extend(field_lines(schema, {"params", "required"}))
        params = schema.get("params", {})
        required = schema.get("required", [])
        if not isinstance(params, dict) or not isinstance(required, list):
            raise ValueError(f"Invalid parameters for {name} action {action}")
        if any(param not in params for param in required):
            raise ValueError(
                f"required parameters are not declared for {name} action {action}"
            )
        if params:
            lines.extend(["Parameters:", ""])
            for param, details in sorted(params.items()):
                lines.extend(parameter_lines(param, details, param in required))
            lines.append("")
    if not actions:
        lines.extend(["This charm declares no actions.", ""])
    return "\n".join(lines)


def render_reference(data):
    name = data["name"]
    if name not in {"k8s", "k8s-worker"}:
        raise ValueError(f"Unexpected charm name: {name}")
    options = data.get("config", {}).get("options", {})
    actions = data.get("actions") or {}
    if not isinstance(options, dict) or not isinstance(actions, dict):
        raise ValueError(f"{name} options and actions must be mappings")

    return {
        f"{name}-config.md": render_config(name, options),
        f"{name}-actions.md": render_actions(name, actions),
    }


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("charmcraft_files", nargs="+", type=Path)
    parser.add_argument("--output-dir", "-o", type=Path, default=Path("."))
    args = parser.parse_args(argv)
    try:
        outputs = {}
        for charmcraft_file in args.charmcraft_files:
            data = yaml.safe_load(charmcraft_file.read_text())
            if not isinstance(data, dict):
                raise ValueError(f"{charmcraft_file} must contain a charmcraft mapping")
            generated = render_reference(data)
            if outputs.keys() & generated.keys():
                raise ValueError(f"Duplicate charm name in {charmcraft_file}")
            outputs.update(generated)
        args.output_dir.mkdir(parents=True, exist_ok=True)
        for filename, content in outputs.items():
            output = args.output_dir / filename
            output.write_text(content)
            print(f"Generated {output}")
    except (OSError, ValueError, TypeError, AttributeError, yaml.YAMLError) as error:
        print(f"Error generating charm reference: {error}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
